/**
 * The roster as the board's contract has to hold it: a stable number per creature, its
 * bead count, and its strings packed two bytes each.
 *
 * Ids are assigned once and never move. `SnarlBoard.addCreature` is permanent, so a
 * creature's number is part of the record the moment it is registered; reordering the
 * game's roster must not renumber anything. New creatures take the next free number.
 * `test/chain-fixtures.test.ts` checks this file against the game's own data.
 *
 *   node scripts/roster.mjs           prints the roster
 *   node scripts/roster.mjs --update  rewrites contracts/test/fixtures/roster.json
 */
import { readFileSync, writeFileSync } from "node:fs";
import { registerHooks } from "node:module";
import { dirname, resolve as resolvePath } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = (...parts) => resolvePath(here, "..", "src", ...parts);
const OUT = resolvePath(here, "..", "contracts", "test", "fixtures", "roster.json");

// The game's modules import each other the way TypeScript does, without extensions. Node
// strips the types but still wants a real filename, so relative misses get one.
registerHooks({
  resolve(specifier, context, nextResolve) {
    try {
      return nextResolve(specifier, context);
    } catch (error) {
      if (!specifier.startsWith(".")) throw error;
      return nextResolve(`${specifier}.ts`, context);
    }
  },
});

const { ALL_CREATURES } = await import(src("data", "creatures.ts"));
const { packEdges, toChainPositions, exactCrossings } = await import(src("engine", "exact.ts"));

let existing = { note: "", creatures: [] };
try {
  existing = JSON.parse(readFileSync(OUT, "utf8"));
} catch {
  // First run.
}

const bySlug = new Map(existing.creatures.map((c) => [c.slug, c]));
let next = existing.creatures.reduce((max, c) => Math.max(max, c.id), -1) + 1;

const creatures = ALL_CREATURES.map((creature) => {
  const id = bySlug.get(creature.id)?.id ?? next++;
  // The creature's true shape, on the chain's grid. Every roster entry is planar here
  // under the contract's own exact rule, which is what makes every puzzle winnable.
  const { xs, ys } = toChainPositions(creature.nodes);
  const crossings = exactCrossings(xs, ys, creature.edges);
  if (crossings !== 0) throw new Error(`${creature.id} crosses itself ${crossings} times`);

  return {
    id,
    slug: creature.id,
    name: creature.name,
    beads: creature.nodes.length,
    edges: packEdges(creature.edges),
    solved: { xs: xs.map(String), ys: ys.map(String) },
  };
}).sort((a, b) => a.id - b.id);

if (creatures.length > 256) throw new Error("the board numbers creatures in one byte");
const ids = new Set(creatures.map((c) => c.id));
if (ids.size !== creatures.length) throw new Error("two creatures share a number");

const out = {
  note: "Generated by scripts/roster.mjs. Ids are permanent once registered on chain; never renumber.",
  creatures,
};
const text = `${JSON.stringify(out, null, 2)}\n`;
if (process.argv.includes("--update")) {
  writeFileSync(OUT, text);
  console.log(`wrote ${creatures.length} creatures`);
} else {
  process.stdout.write(text);
}
