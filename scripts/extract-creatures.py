"""One-shot codegen: reference/snarl-lib.js -> src/data/creatures.ts.

The roster was authored in the design prototype, where each creature's coordinates are
its true planar shape. Transcribing ~200 coordinate pairs by hand is how you get an
unsolvable puzzle, so it is parsed instead. Kept for provenance and in case the
reference roster is revised; the generated file is the one that ships.

    python3 -I scripts/extract-creatures.py
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "reference" / "snarl-lib.js"
OUT = ROOT / "src" / "data" / "creatures.ts"


def objects(src: str, start: int) -> list[str]:
    """Brace-matched top-level object literals of the array starting at `start`."""
    out, depth, begin = [], 0, None
    i = start
    while i < len(src):
        ch = src[i]
        if ch == "[" and depth == 0 and begin is None and out == []:
            pass
        if ch == "{":
            if depth == 0:
                begin = i
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0 and begin is not None:
                out.append(src[begin : i + 1])
                begin = None
        elif ch == "]" and depth == 0 and out:
            break
        i += 1
    return out


def pairs(block: str) -> list[tuple[float, float]]:
    return [(float(a), float(b)) for a, b in re.findall(r"\[(-?[\d.]+),(-?[\d.]+)\]", block)]


def field(block: str, name: str) -> str | None:
    m = re.search(rf"\b{name}:'((?:[^'\\]|\\.)*)'", block)
    return m.group(1).replace("\\'", "'") if m else None


def number(block: str, name: str) -> float | None:
    m = re.search(rf"\b{name}:(-?[\d.]+)", block)
    return float(m.group(1)) if m else None


def parse(block: str) -> dict:
    nodes_m = re.search(r"nodes:(\[\[.*?\]\]),edges:", block, re.S)
    edges_m = re.search(r"edges:E\('([^']*)'\)", block)
    scr_m = re.search(r"scrambled:(\[\[.*?\]\])", block, re.S)
    tgt_m = re.search(r"target:\[(\d+),(\d+)\]", block)
    if not nodes_m or not edges_m:
        raise SystemExit(f"could not parse creature block: {block[:60]}")
    return {
        "id": field(block, "id"),
        "name": field(block, "name"),
        "shape": field(block, "shape"),
        "hue": number(block, "hue"),
        "chroma": number(block, "chroma"),
        "lore": field(block, "lore"),
        "sound": field(block, "sound"),
        "move": field(block, "move"),
        "idle": field(block, "idle"),
        "tap": field(block, "tap"),
        "target": (int(tgt_m.group(1)), int(tgt_m.group(2))) if tgt_m else None,
        "par": number(block, "par"),
        "nodes": pairs(nodes_m.group(1)),
        "edges": [tuple(int(x) for x in p.split("-")) for p in edges_m.group(1).split()],
        "eye": int(number(block, "eye")),
        "scrambled": pairs(scr_m.group(1)) if scr_m else None,
        "rare": "rare:true" in block,
    }


def num(v: float) -> str:
    return str(int(v)) if float(v).is_integer() else str(v)


def emit(c: dict) -> str:
    lines = [
        "  {",
        f"    id: {c['id']!r},".replace("'", '"'),
        f"    name: {c['name']!r},".replace("'", '"'),
        f"    shape: {c['shape']!r},".replace("'", '"'),
        f"    hue: {num(c['hue'])},",
    ]
    if c["chroma"] is not None:
        lines.append(f"    chroma: {num(c['chroma'])},")
    lines.append(f'    lore: "{c["lore"]}",')
    lines.append(f'    sound: "{c["sound"]}",')
    lines.append(f'    move: "{c["move"]}",')
    if c["idle"]:
        lines.append(f'    idle: "{c["idle"]}",')
    if c["tap"]:
        lines.append(f'    tap: "{c["tap"]}",')
    if c["target"]:
        lines.append(f"    target: [{c['target'][0]}, {c['target'][1]}],")
    lines.append(f"    par: {num(c['par'])},")
    nodes = ", ".join(f"[{num(x)}, {num(y)}]" for x, y in c["nodes"])
    lines.append(f"    nodes: [{nodes}],")
    edges = ", ".join(f"[{a}, {b}]" for a, b in c["edges"])
    lines.append(f"    edges: [{edges}],")
    lines.append(f"    eye: {c['eye']},")
    if c["scrambled"]:
        scr = ", ".join(f"[{num(x)}, {num(y)}]" for x, y in c["scrambled"])
        lines.append(f"    scrambled: [{scr}],")
    if c["rare"]:
        lines.append("    rare: true,")
    lines.append("  },")
    return "\n".join(lines)


def main() -> None:
    src = SRC.read_text()
    groups = {}
    for name in ("CREATURES", "TUTORIAL"):
        m = re.search(rf"const {name}=\[", src)
        if not m:
            raise SystemExit(f"{name} not found")
        groups[name] = [parse(b) for b in objects(src, m.end())]
    rare_m = re.search(r"const RARE=(\{.*?\});", src, re.S)
    if not rare_m:
        raise SystemExit("RARE not found")
    rare = parse(rare_m.group(1))

    body = [
        "// Generated by scripts/extract-creatures.py from reference/snarl-lib.js.",
        "// Every roster below is planar at solvedLayout(nodes); test/engine.test.ts enforces it.",
        "",
        'import type { Creature } from "~/engine";',
        "",
        "/** The two knots of the tutorial, in order. */",
        "export const TUTORIAL: readonly Creature[] = [",
        *[emit(c) for c in groups["TUTORIAL"]],
        "];",
        "",
        "/** World 1, easiest first: 6 beads and par 3 up to 24 beads and par 14. */",
        "export const CREATURES: readonly Creature[] = [",
        *[emit(c) for c in groups["CREATURES"]],
        "];",
        "",
        "/** The Daily Snarl's rare creature. */",
        "export const RARE: Creature = {",
        *emit(rare).split("\n")[1:-1],
        "};",
        "",
        "export const ALL_CREATURES: readonly Creature[] = [...TUTORIAL, ...CREATURES, RARE];",
        "",
        "export const creatureById = (id: string): Creature | undefined =>",
        "  ALL_CREATURES.find((c) => c.id === id);",
        "",
    ]
    OUT.write_text("\n".join(body))
    print(
        f"wrote {OUT.relative_to(ROOT)}: "
        f"{len(groups['TUTORIAL'])} tutorial, {len(groups['CREATURES'])} world 1, 1 rare",
        file=sys.stderr,
    )


main()
