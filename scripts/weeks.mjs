/** ISO week number and year for a UTC instant. */
function isoWeek(d) {
  const t = new Date(Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate()));
  const day = (t.getUTCDay() + 6) % 7;            // Monday = 0
  t.setUTCDate(t.getUTCDate() - day + 3);         // the week's Thursday
  const firstThursday = new Date(Date.UTC(t.getUTCFullYear(), 0, 4));
  const firstDay = (firstThursday.getUTCDay() + 6) % 7;
  firstThursday.setUTCDate(firstThursday.getUTCDate() - firstDay + 3);
  const week = 1 + Math.round((t - firstThursday) / (7 * 864e5));
  return { year: t.getUTCFullYear(), week };
}

const HOUR = 3600_000;
const now = new Date();
// Monday 12:00 UTC of the current ISO week: midday everywhere on earth's Monday, so the
// label is the same whatever timezone a player is in.
const monday = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate(), 12));
monday.setUTCDate(monday.getUTCDate() - ((monday.getUTCDay() + 6) % 7));

const weeks = [];
for (let i = 0; i < 26; i++) {
  const mondayNoon = new Date(monday.getTime() + i * 7 * 24 * HOUR);
  const { year, week } = isoWeek(mondayNoon);
  const label = `${year}-W${String(week).padStart(2, "0")}`;
  const closesAt = new Date(mondayNoon.getTime() + 7 * 24 * HOUR);
  weeks.push({
    label,
    id: year * 100 + week,
    mondayNoonUtc: mondayNoon.toISOString(),
    // The week is over for the last player on earth at Sunday midnight in UTC-12, which
    // is Monday noon UTC. The player's week is local; the contract's is one timestamp.
    closesAt: Math.floor(closesAt.getTime() / 1000),
    // It is already Monday for the first player on earth 26 hours before that, at
    // Sunday 10:00 UTC. The week must be open by then.
    openBy: Math.floor((mondayNoon.getTime() - 26 * HOUR) / 1000),
    // Ninety days to come and collect. The contract allows any window; this is a phone
    // game whose players are claiming a daily UBI, and "we took what you earned because
    // you did not come back within a week" is not a sentence worth risking for the sake
    // of rolling a pool over sooner.
    sweepableAt: Math.floor((closesAt.getTime() + 90 * 24 * HOUR) / 1000),
  });
}

